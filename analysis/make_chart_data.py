#!/usr/bin/env python3
"""Emit chart_data.js for the eye-adaptation tradeoff chart."""
import json
import os

src = open(os.path.join(os.path.dirname(__file__), "eye_adaptation.py")).read()
defs = src.split('print("=" * 88)')[0]
ns = {}
exec(defs, ns)

run_step = ns["run_step"]
run_spike = ns["run_spike"]
settle_time = ns["settle_time"]
spike_overshoot = ns["spike_overshoot"]
JUMPS, NAMES, JND, FPS = ns["JUMPS"], ns["NAMES"], ns["JND"], ns["FPS"]

ws = list(range(0, 61)) + [75, 90]

overshoot = {ds: {"dE": [], "disp": []} for ds in (1.0, 2.0, 3.0)}
for w in ws:
    for ds in (1.0, 2.0, 3.0):
        tr, e0 = run_spike(2.0, w, ds)          # 100x background
        pk_E, pk_D, _ = spike_overshoot(tr, e0)
        overshoot[ds]["dE"].append(round(pk_E / JND, 3))
        overshoot[ds]["disp"].append(round(pk_D / JND, 3))

adapt = {j: [] for j in JUMPS}
for w in ws:
    for j in JUMPS:
        adapt[j].append(round(settle_time(run_step(j, w), j), 3))

# 100x step, W=0: visible flash decay, first 2 s
trace100 = run_step(2.0, 0)
step_trace = [{"t": round(t, 4), "disp_jnd": round(od / JND, 3)}
              for (t, _, od) in trace100 if t <= 2.0]

# constraint points
wmin = {}
for ds in (1.0, 2.0, 3.0):
    for w in range(400):
        tr, e0 = run_spike(2.0, w, ds)
        pk_E, pk_D, _ = spike_overshoot(tr, e0)
        if pk_E <= JND and pk_D <= JND:
            wmin[ds] = w
            break
conflict = {
    "ds": 3.0,
    "w_min": wmin[3.0],
    "t_adapt_1000x_at_wmin": round(settle_time(run_step(3.0, wmin[3.0]), 3.0), 3),
    "w_time_limit": max(w for w in range(120)
                        if settle_time(run_step(3.0, w), 3.0) <= 1.0),
}

data = {
    "W_frames": ws,
    "W_ms": [round(w / FPS * 1000) for w in ws],
    "overshoot": {str(k): v for k, v in overshoot.items()},
    "adapt": {NAMES[j]: v for j, v in adapt.items()},
    "step_trace_100x": step_trace,
    "w_min": {str(k): v for k, v in wmin.items()},
    "conflict": conflict,
    "constants": {"tau_s": ns["TAU"], "a": round(ns["A"], 5),
                  "tau_frames": round(ns["TAU_FRAMES"], 1),
                  "jnd_log10": JND, "budget_s": ns["T_BUDGET"], "fps": FPS},
}

out = os.path.join(os.path.dirname(__file__), "chart_data.js")
with open(out, "w") as f:
    f.write("// auto-generated by make_chart_data.py\n")
    f.write("const CHART_DATA = ")
    f.write(json.dumps(data, indent=2))
    f.write(";\n")
print("wrote", out)
print("w_min:", wmin, " conflict:", conflict)
